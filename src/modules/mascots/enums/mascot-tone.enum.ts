export enum MascotTone {
  /**
   * Thấu cảm, ấm áp, động viên, không phán xét.
   * Tập trung khích lệ tinh thần và hướng dẫn các bước tiết kiệm nhẹ nhàng.
   */
  GENTLE = 'GENTLE',

  /**
   * Cân bằng, khách quan, phân tích logic tài chính (Mặc định).
   * Đưa ra nhận xét thực tế, số liệu và giải pháp chuẩn mực.
   */
  BALANCED = 'BALANCED',

  /**
   * Nghiêm khắc, hài hước, cà khịa nhẹ nhàng để cảnh tỉnh.
   * Dành cho người dùng thích phong cách trào phúng, thẳng thắn để ngừng tiêu hoang.
   */
  ROAST = 'ROAST',
}
